"""Writes a SYNTHETIC Gaussian-splat world of the default kitchen in Image-Blaster's on-disk layout.

This is not an Image-Blaster/Marble generation. It exists to exercise the Spark splat-loading
path, Image-Blaster's flip_y convention, and world-to-scene alignment without a paid API key.

    python scripts/make_test_splat.py            # -> worlds/synthetic-kitchen/
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from echo.config import get_settings  # noqa: E402
from echo.spatial.kitchen import default_kitchen  # noqa: E402

SH_C0 = 0.28209479177387814
SLUG = "synthetic-kitchen"


def _box_surface(rng, center, size, color, density=900):
    (cx, cy), (sx, sy, sz) = center, size
    area = 2 * (sx * sy + sx * sz + sy * sz)
    n = max(200, int(area * density))
    pts = []
    for _ in range(n):
        face = rng.integers(0, 5)  # no bottom face
        u, v = rng.random(2)
        if face == 0:
            p = (cx - sx / 2 + u * sx, cy - sy / 2 + v * sy, sz)
        elif face == 1:
            p = (cx - sx / 2 + u * sx, cy - sy / 2, v * sz)
        elif face == 2:
            p = (cx - sx / 2 + u * sx, cy + sy / 2, v * sz)
        elif face == 3:
            p = (cx - sx / 2, cy - sy / 2 + u * sy, v * sz)
        else:
            p = (cx + sx / 2, cy - sy / 2 + u * sy, v * sz)
        pts.append(p)
    pts = np.array(pts)
    shade = 0.85 + 0.15 * (pts[:, 2] / max(sz, 1e-3))
    cols = np.clip(np.array(color)[None, :] * shade[:, None] + rng.normal(0, 0.03, (len(pts), 3)), 0, 1)
    return pts, cols


def build(rng: np.random.Generator):
    model = default_kitchen()
    w, d = model.width_m, model.depth_m
    chunks_p, chunks_c = [], []

    # Floor: tiled quarry tile pattern.
    n = 70000
    floor = np.column_stack([rng.random(n) * w, rng.random(n) * d, np.zeros(n)])
    tile = ((np.floor(floor[:, 0] / 0.3) + np.floor(floor[:, 1] / 0.3)) % 2)[:, None]
    floor_col = np.where(tile > 0, [0.42, 0.30, 0.24], [0.36, 0.26, 0.21]) + rng.normal(0, 0.02, (n, 3))
    chunks_p.append(floor)
    chunks_c.append(np.clip(floor_col, 0, 1))

    # Back (north) and west walls, 2.6 m high, white tile.
    for axis in ("north", "west"):
        m = 30000
        h = rng.random(m) * 2.6
        if axis == "north":
            pts = np.column_stack([rng.random(m) * w, np.full(m, d), h])
        else:
            pts = np.column_stack([np.zeros(m), rng.random(m) * d, h])
        chunks_p.append(pts)
        chunks_c.append(np.clip(np.full((m, 3), 0.86) + rng.normal(0, 0.03, (m, 3)), 0, 1))

    palette = {"counter": (0.75, 0.76, 0.78), "appliance": (0.42, 0.43, 0.46), "shelf": (0.55, 0.42, 0.30)}
    for fx in model.fixtures:
        p, c = _box_surface(rng, fx.center, fx.size, palette.get(fx.kind, (0.7, 0.7, 0.7)))
        chunks_p.append(p)
        chunks_c.append(c)

    world = np.concatenate(chunks_p)
    colors = np.concatenate(chunks_c)
    # World (x, y, z-up) -> render (x, z, -y), then pre-apply Image-Blaster's flip_y (PI about X):
    # (x, y, z) -> (x, -y, -z). The viewer's flip undoes it.
    render = np.column_stack([world[:, 0], world[:, 2], -world[:, 1]])
    stored = np.column_stack([render[:, 0], -render[:, 1], -render[:, 2]])
    return stored.astype(np.float32), colors.astype(np.float32)


def write_ply(path: Path, positions: np.ndarray, colors: np.ndarray, rng: np.random.Generator) -> None:
    n = len(positions)
    scale = np.log(np.full((n, 3), 0.018, np.float32) * (0.7 + 0.6 * rng.random((n, 1)).astype(np.float32)))
    opacity_logit = np.full((n, 1), 3.0, np.float32)
    rot = np.zeros((n, 4), np.float32)
    rot[:, 0] = 1.0
    f_dc = ((colors - 0.5) / SH_C0).astype(np.float32)
    fields = ["x", "y", "z", "f_dc_0", "f_dc_1", "f_dc_2", "opacity", "scale_0", "scale_1", "scale_2", "rot_0", "rot_1", "rot_2", "rot_3"]
    data = np.hstack([positions, f_dc, opacity_logit, scale, rot]).astype("<f4")
    header = "ply\nformat binary_little_endian 1.0\n" f"element vertex {n}\n" + "".join(f"property float {f}\n" for f in fields) + "end_header\n"
    with path.open("wb") as fh:
        fh.write(header.encode("ascii"))
        fh.write(data.tobytes())


def main() -> None:
    settings = get_settings()
    out_dir = settings.worlds_dir / SLUG / "output" / "world"
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(11)
    positions, colors = build(rng)
    ply = out_dir / "0-world-full_res.ply"
    write_ply(ply, positions, colors, rng)
    manifest = {
        "world_id": "echo-synthetic-kitchen",
        "display_name": "Synthetic kitchen splat",
        "echo_synthetic": True,
        "echo_notes": "SYNTHETIC test splat generated by backend/scripts/make_test_splat.py from the spatial model. Not produced by Image-Blaster or World Labs.",
        "assets": {"splats": {"spz_urls": {"full_res": "0-world-full_res.ply"}, "semantics_metadata": {"metric_scale_factor": 1.0, "ground_plane_offset": 0.0, "flip_y": True}}},
    }
    (out_dir / "0-world.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (settings.worlds_dir / SLUG / "project.json").write_text(json.dumps({"slug": SLUG, "display_name": "Synthetic kitchen (test splat)"}, indent=2) + "\n")
    print(f"wrote {len(positions)} splats -> {ply} ({ply.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
